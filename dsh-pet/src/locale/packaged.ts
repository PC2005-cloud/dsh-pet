function sameSlot(left: readonly string[], right: readonly string[]): boolean {
  return left.length === right.length && left.every((line, index) => line === right[index]);
}

/**
 * 按档替换包内工作状态短语。某一档与包内不完全一致时，这一档保持原样。
 *
 * @param localeId - 宿主语言；不是 `ru` 时原样返回。
 * @param texts - 生效配置；缺省则原样。
 */
export function localizedWorkStatusTexts(
  localeId: string | undefined | null,
  texts: readonly (readonly string[])[] | undefined,
): readonly (readonly string[])[] | undefined {
  if (texts === undefined) return undefined;
  if (localeId !== 'ru') return texts;
  return texts.map((slot, index) => {
    const packaged = PACKAGED_WORK_STATUS[index];
    const russian = RU_WORK_STATUS[index];
    if (packaged === undefined || russian === undefined || !sameSlot(slot, packaged)) return slot;
    return russian;
  });
}

/**
 * 单条表情包描述：与包内原文一致才换成俄文。
 *
 * @param localeId - 宿主语言。
 * @param name - 表情包键。
 * @param desc - 生效描述。
 */
/**
 * 悬浮提示上的显示名。包内默认名在 ru 时换成俄文；人改过的名字原样返回。
 *
 * @param localeId - 宿主语言；不是 `ru` 时原样返回。
 * @param name - 生效配置里的显示名。
 */
export function localizedPetName(localeId: string | undefined | null, name: string): string {
  if (localeId === 'ru' && name === PACKAGED_PET_NAME) return RU_PET_NAME;
  return name;
}

/**
 * 发给模型的人设正文。包内默认在 ru 时换成俄文；人改过的原文返回。
 *
 * @param localeId - 宿主语言；不是 `ru` 时原样返回。
 * @param prompt - 生效的 whisperPrompt。
 */
export function localizedWhisperPrompt(localeId: string | undefined | null, prompt: string): string {
  if (localeId === 'ru' && prompt === PACKAGED_WHISPER_PROMPT) return RU_WHISPER_PROMPT;
  return prompt;
}

export function localizeMemeDescription(localeId: string | undefined | null, name: string, desc: string): string {
  if (localeId !== 'ru') return desc;
  const packaged = PACKAGED_MEME_DESC[name];
  if (packaged === undefined || desc !== packaged) return desc;
  return RU_MEME_DESC[name] ?? desc;
}
