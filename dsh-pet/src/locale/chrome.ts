/** 固定界面文案的键。 */
export type ChromeKey = keyof typeof zh;

/** 中文键集，测试与页面替换用。 */
export const chromeZh: { [K in ChromeKey]: string } = zh;

/** 俄文键集，与中文一一对应。 */
export const chromeRu: { [K in ChromeKey]: string } = ru;

/** `ru` 取俄文，其余（含空）取中文。 */
export function chromeText(id: string | undefined | null, key: ChromeKey): string {
  return id === 'ru' ? ru[key] : zh[key];
}

/** 把 `{name}` 换成值；缺的占位符留在原文里。 */
export function fillChrome(
  id: string | undefined | null,
  key: ChromeKey,
  vars: Readonly<Record<string, string | number>>,
): string {
  return chromeText(id, key).replace(/\{(\w+)\}/g, (token, name: string) =>
    Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : token,
  );
}
