def post_json(url, payload, headers=None, timeout=60):
    data = json.dumps(payload, ensure_ascii=False).encode("utf-8")
    req = urllib.request.Request(url, data=data, method="POST")
    req.add_header("Content-Type", "application/json")
    for k, v in (headers or {}).items():
        req.add_header(k, v)
    with urllib.request.urlopen(req, timeout=timeout) as resp:
        return json.loads(resp.read().decode("utf-8"))


def get_json(url, headers=None, timeout=60):
    req = urllib.request.Request(url, method="GET")
    for k, v in (headers or {}).items():
        req.add_header(k, v)
    with urllib.request.urlopen(req, timeout=timeout) as resp:
        return json.loads(resp.read().decode("utf-8"))


def download(url, dest):
    with urllib.request.urlopen(url, timeout=300) as resp, open(dest, "wb") as f:
        f.write(resp.read())


def extract_video_url(output):
    if isinstance(output.get("video_url"), str):
        return output["video_url"]
    for key in ("video", "videos", "results"):
        items = output.get(key)
        if isinstance(items, list) and items:
            first = items[0]
            if isinstance(first, str):
                return first
            if isinstance(first, dict):
                return first.get("url") or first.get("video_url")
    return None


def main() -> int:
    api_key = os.environ.get("DASHSCOPE_API_KEY", "").strip()
    if not api_key:
        print("ERROR: 未设置环境变量 DASHSCOPE_API_KEY", flush=True)
        return 2
    if not REF_IMAGE.exists():
        print(f"ERROR: 参考图不存在: {REF_IMAGE}", flush=True)
        return 2
    OUT_DIR.mkdir(parents=True, exist_ok=True)

    b64 = base64.b64encode(REF_IMAGE.read_bytes()).decode("ascii")
    img_data_uri = f"data:image/png;base64,{b64}"
    auth = {"Authorization": f"Bearer {api_key}"}

    tasks = []
    for name, action in ACTIONS:
        prompt = f"{CHARACTER}\n{GLOBAL_RULES}\n{action}"
        payload = {
            "model": MODEL,
            "input": {
                "prompt": prompt,
                "media": [{"type": "reference_image", "url": img_data_uri}],
            },
            "parameters": {
                "resolution": "720P",
                "ratio": "16:9",
                "duration": 10,
                "audio": False,
                "watermark": False,
                "prompt_extend": False,
            },
        }
        try:
            resp = post_json(ENDPOINT, payload, headers={**auth, "X-DashScope-Async": "enable"})
            task_id = resp["output"]["task_id"]
        except urllib.error.HTTPError as e:
            body = e.read().decode("utf-8", "replace")
            print(f"[提交失败] {name}: HTTP {e.code} {body[:300]}", flush=True)
            continue
        tasks.append((name, task_id, OUT_DIR / f"{name}.mp4"))
        print(f"[已提交 {len(tasks):02d}/{len(ACTIONS)}] {name}  {task_id}", flush=True)

    if not tasks:
        return 1

    pending = {tid: (name, dest) for name, tid, dest in tasks}
    start = time.time()
    MAX_WAIT = 1800
    while pending and time.time() - start < MAX_WAIT:
        time.sleep(8)
        for tid in list(pending.keys()):
            name, dest = pending[tid]
            try:
                resp = get_json(TASK_URL.format(task_id=tid), headers=auth)
            except urllib.error.HTTPError as e:
                print(f"[查询异常] {name}: HTTP {e.code}", flush=True)
                continue
            output = resp.get("output", {})
            status = output.get("task_status", "")
            if status == "SUCCEEDED":
                video_url = extract_video_url(output)
                if video_url:
                    download(video_url, dest)
                    print(f"[完成 {len(tasks)-len(pending)+1}/{len(tasks)}] {name}", flush=True)
                else:
                    print(f"[失败] {name}: 无视频地址 {json.dumps(output, ensure_ascii=False)[:300]}", flush=True)
                pending.pop(tid)
            elif status in ("FAILED", "CANCELED", "UNKNOWN"):
                print(f"[失败] {name}: {status} {json.dumps(output, ensure_ascii=False)[:300]}", flush=True)
                pending.pop(tid)

    running = len(pending)
    if running:
        print(f"TIMEOUT: {running} 个任务未完成: " + ", ".join(n for n, _ in pending.values()), flush=True)
        return 1
    print("全部任务结束。", flush=True)
    return 0


if __name__ == "__main__":
    sys.exit(main())
